static caelus::causal::EngineSnapshot run_repl_tick(
    caelus::causal::CausalEngine& engine,
    const std::string& scenario_id,
    bool scenario_active,
    caelus::neural::NeuralControllerV1* neural_controller,
    uint64_t audit_session_id,
    bool det_mode) {
    const uint64_t tick_before = engine.current_tick();
    g_tick_ctr.store(tick_before, std::memory_order_relaxed);
    DispatchConnectorsReported(engine, tick_before);
    audit_intel_rejections();

    caelus::causal::EngineSnapshot snap = engine.run_ticks(1);
    if (neural_controller != nullptr && neural_controller->enabled()) {
        if (!neural_controller->observe_tick(engine)) {
            std::cerr << "[NEURAL] Graph history observation failed; "
                         "symbolic-only fallback is now active.\n";
            neural_controller->force_symbolic_fallback();
        } else {
            ProcessNeuralTick(
                *neural_controller, engine, audit_session_id, det_mode);
        }
    }
    g_emitter.emit(caelus::ws_json::friction(
        snap.clamped_friction_d(),
        snap.outage_active ? 3 : (snap.regime_exceeded ? 2 : 0),
        engine.current_tick()));
    g_emitter.emit(caelus::ws_json::engine_state(
        scenario_active ? "SCENARIO_ACTIVE" : "AWAITING_SCENARIO_INJECTION",
        scenario_id, engine.current_tick(),
        snap.clamped_friction_d(), snap.throughput_ratio,
        snap.outage_active, snap.any_hysteresis_flip));

    if (g_audit.is_open()) {
        std::ostringstream ss;
        ss << std::fixed << std::setprecision(6);
        ss << "{\"type\":\"REPL_TICK\","
           << "\"tick_before\":" << tick_before
           << ",\"tick_after\":" << engine.current_tick()
           << ",\"raw_friction\":" << snap.raw_friction_d()
           << ",\"clamped_friction\":" << snap.clamped_friction_d()
           << ",\"regime_exceeded\":" << (snap.regime_exceeded ? "true" : "false")
           << ",\"outage\":" << (snap.outage_active ? "true" : "false")
           << ",\"deadline_missed\":" << (snap.any_deadline_missed ? "true" : "false")
           << ",\"hysteresis_flip\":" << (snap.any_hysteresis_flip ? "true" : "false")
           << "}";
        g_audit.append(ss.str());
    }

    // War Room canlı yayını: throughput göstergesi + gerçek graf snapshot'ı.
    // Yalnız bir tarayıcı bağlıyken serileştirme maliyetine gireriz.
    if (g_emitter.connected()) {
        g_emitter.emit(caelus::ws_json::engine_state(
            g_scenario_id.empty() ? "LIVE" : g_scenario_id, g_scenario_id,
            engine.current_tick(), snap.clamped_friction_d(),
            snap.throughput_ratio, snap.outage_active, snap.any_hysteresis_flip));
        emit_ws_snapshot(engine, g_scenario_id);
    }

    return snap;
}

static caelus::causal::EngineSnapshot RunScenarioRepl(
    caelus::causal::CausalEngine& engine,
    caelus::ScenarioPack& pack,
    bool& pack_loaded,
    std::string& scenario_id,
    caelus::causal::EngineSnapshot last_snap,
    caelus::neural::NeuralControllerV1* neural_controller,
    uint64_t audit_session_id,
    bool det_mode,
    caelus::CsvReplayConnector* scenario_replay,
    std::string& scenario_replay_path) {
    const auto run_tick = [&]() {
        if (pack_loaded && scenario_replay_path.empty()) {
            pack.inject_intel_at(engine, engine.current_tick());
        }
        return run_repl_tick(engine, scenario_id, pack_loaded, neural_controller,
                             audit_session_id, det_mode);
    };
    std::cout << "\n[REPL] Senaryo REPL basladi. Yardim icin 'help', cikis icin 'quit'.\n";
    print_repl_snapshot(engine, last_snap);

    // War Room tarayıcısından gelen komutları (WS text frame) da bu REPL'e
    // yönlendir: gerçek motor sürülür, snapshot geri yayınlanır. Handler
    // emitter thread'inde koşar, sadece kuyruğa iter (motora dokunmaz).
    g_emitter.on_command([](std::string c){ g_repl_cmds.push(std::move(c)); });

    // stdin ayrı bir thread'de okunup aynı kuyruğa beslenir; ana döngü tek
    // tüketici olarak terminal + tarayıcı komutlarını sırayla işler.
    std::thread stdin_thread([]{
        std::string in;
        while (std::getline(std::cin, in)) g_repl_cmds.push(in);
        g_repl_cmds.close();
    });
    stdin_thread.detach();

    std::string line;
    while (true) {
        std::cout << "\ncaelus:" << scenario_id << " t=" << engine.current_tick() << "> ";
        if (!g_repl_cmds.pop(line)) {
            std::cout << "\n[REPL] stdin kapandi, cikiliyor.\n";
            break;
        }

        const std::string command_line = trim_copy(line);
        if (command_line.empty()) continue;

        std::istringstream iss(command_line);
        std::string cmd;
        iss >> cmd;
        std::transform(cmd.begin(), cmd.end(), cmd.begin(),
                       [](unsigned char c){ return static_cast<char>(std::tolower(c)); });

        if (cmd == "quit" || cmd == "exit") {
            audit_repl_event(command_line, engine, "quit");
            std::cout << "[REPL] Cikis.\n";
            break;
        }
        if (cmd == "help" || cmd == "?") {
            print_repl_help();
            audit_repl_event(command_line, engine, "ok");
            continue;
        }
        if (cmd == "status" || cmd == "snapshot") {
            std::string format;
            iss >> format;
            std::transform(format.begin(), format.end(), format.begin(),
                           [](unsigned char c){ return static_cast<char>(std::tolower(c)); });
            if (format == "--json" || format == "json") {
                print_repl_snapshot_json(scenario_id, engine, last_snap);
            } else {
                print_repl_snapshot(engine, last_snap);
                if (pack_loaded) {
                    std::cout << "[REPL_SCENARIO_LOADED] " << build_scenario_loaded_json(pack) << "\n";
                }
            }
            // War Room "ANALİZ ET" bu komutu gönderir: gerçek graf snapshot'ını
            // WS üzerinden geri yayınla (analiz paneli motorun canlı verisiyle dolar).
            if (g_emitter.connected()) {
                if (pack_loaded) emit_ws_scenario_loaded(pack);
                emit_ws_scenario_model(pack, pack_loaded);
                emit_ws_snapshot(engine, g_scenario_id);
            }
            audit_repl_event(command_line, engine, "ok");
            continue;
        }
        if (cmd == "list") {
            std::string what;
            iss >> what;
            std::transform(what.begin(), what.end(), what.begin(),
                           [](unsigned char c){ return static_cast<char>(std::tolower(c)); });
            if (what == "levers") {
                print_repl_levers(pack, pack_loaded);
                // War Room lever konsolu: gerçek kaldıraç listesini WS'e yayınla
                // (UI'daki hardcoded ipuçları yerine motorun paketinden gelir).
                if (g_emitter.connected()) {
                    std::ostringstream lo;
                    lo << "{\"type\":\"levers\",\"scenario_id\":\""
                       << json_escape(g_scenario_id) << "\",\"levers\":[";
                    bool lf = true;
                    if (pack_loaded) {
                        for (size_t li = 0; li < pack.levers.size(); ++li) {
                            const auto& lv = pack.levers[li];
                            const caelus::ScenarioPack::LeverMeta* lm =
                                (li < pack.lever_meta.size()) ? &pack.lever_meta[li] : nullptr;
                            if (!lf) lo << ",";
                            lf = false;
                            lo << "{\"id\":\"" << json_escape(lv.id) << "\","
                               << "\"code\":\"" << json_escape(lm ? lm->code : lv.id) << "\","
                               << "\"label\":\"" << json_escape(lm ? lm->label : lv.id) << "\","
                               << "\"notes\":\"" << json_escape(lm ? lm->notes : "") << "\","
                               << "\"cost_usd\":" << (lm ? lm->cost_usd : -1.0) << ","
                               << "\"data_source\":\"" << json_escape(lm ? lm->data_source : pack.data_provenance) << "\","
                               << "\"target\":\"" << json_escape(lv.target) << "\","
                               << "\"success_p\":" << std::fixed << std::setprecision(2)
                               << caelus::causal::fp_to_d(lv.success_p_fp) << ","
                               << "\"cost_ticks\":" << lv.cost_ticks << ","
                               << "\"lockout_ticks\":" << lv.lockout_ticks << ","
                               << "\"available\":" << (engine.is_lever_available(lv.id) ? "true" : "false") << ","
                               << "\"remaining_lockout\":" << engine.lever_remaining_lockout(lv.id) << ","
                               << "\"on_success\":";
                            emit_lever_outcome_json(lo, lv.on_success);
                            lo << ",\"on_failure\":";
                            emit_lever_outcome_json(lo, lv.on_failure);
                            lo << "}";
                        }
                    }
                    lo << "]}";
                    g_emitter.emit(lo.str());
                }
                audit_repl_event(command_line, engine, "ok");
            } else {
                std::cout << "[REPL] Bilinmeyen liste. Ornek: list levers\n";
                audit_repl_event(command_line, engine, "error");
            }
            continue;
        }
        if (cmd == "tick") {
            uint64_t n = 1;
            if (iss >> n) {
                if (n == 0 || n > 100000) {
                    std::cout << "[REPL] tick sayisi 1..100000 araliginda olmali.\n";
                    audit_repl_event(command_line, engine, "error");
                    continue;
                }
            }

            for (uint64_t i = 0; i < n; ++i) {
                last_snap = run_tick();
            }
            std::cout << "[REPL] " << n << " tick tamamlandi.\n";
            print_repl_snapshot(engine, last_snap);
            audit_repl_event(command_line, engine, "ok");
            continue;
        }
        if (cmd == "lever") {
            std::string lever_id;
            iss >> lever_id;
            if (lever_id.empty()) {
                std::cout << "[REPL] Kullanim: lever <id>\n";
                audit_repl_event(command_line, engine, "error");
                continue;
            }
            const caelus::causal::Lever* meta =
                pack_loaded ? find_pack_lever(pack, lever_id) : nullptr;
            if (!meta) {
                std::cout << "[REPL] Kaldirac bulunamadi: " << lever_id
                          << " (liste icin: list levers)\n";
                audit_repl_event(command_line, engine, "error");
                continue;
            }

            const caelus::causal::EngineSnapshot before = last_snap;
            const uint64_t tick_before = engine.current_tick();
            const bool success = engine.apply_lever(lever_id);
            const int remaining_cost =
                meta->cost_ticks > 1 ? (meta->cost_ticks - 1) : 0;
            std::cout << "[REPL] Lever sonucu: " << (success ? "BASARILI" : "BASARISIZ/KILITLI")
                      << " | cost_ticks=" << meta->cost_ticks
                      << " (tam maliyet icin ek tick: " << remaining_cost << ")\n";
            last_snap = run_tick();
            print_repl_snapshot(engine, last_snap);
            if (g_emitter.connected()) {
                // Gözlenen (karşı-olgusal DEĞİL) önce/sonra motor durumu.
                std::ostringstream lr;
                lr << std::fixed << std::setprecision(6)
                   << "{\"type\":\"lever_result\",\"scenario_id\":\"" << json_escape(g_scenario_id) << "\","
                   << "\"lever_id\":\"" << json_escape(lever_id) << "\","
                   << "\"success\":" << (success ? "true" : "false") << ","
                   << "\"tick_before\":" << tick_before << ","
                   << "\"tick_after\":" << engine.current_tick() << ","
                   << "\"friction_before\":" << before.clamped_friction_d() << ","
                   << "\"friction_after\":" << last_snap.clamped_friction_d() << ","
                   << "\"throughput_before\":" << before.throughput_ratio << ","
                   << "\"throughput_after\":" << last_snap.throughput_ratio << ","
                   << "\"outage_after\":" << (last_snap.outage_active ? "true" : "false") << "}";
                g_emitter.emit(lr.str());
            }
            audit_repl_event(command_line, engine, success ? "success" : "failed_or_locked");
            continue;
        }
        if (cmd == "compare_lever" || cmd == "counterfactual") {
            std::string lever_id;
            iss >> lever_id;
            if (lever_id.empty()) {
                std::cout << "[REPL] Kullanim: compare_lever <id> [horizon_ticks] [seed]\n";
                audit_repl_event(command_line, engine, "error");
                continue;
            }
            const caelus::causal::Lever* meta =
                pack_loaded ? find_pack_lever(pack, lever_id) : nullptr;
            if (!meta) {
                std::cout << "[REPL] Kaldirac bulunamadi: " << lever_id
                          << " (liste icin: list levers)\n";
                audit_repl_event(command_line, engine, "error");
                continue;
            }
            const caelus::ScenarioPack::LeverMeta* lmeta = nullptr;
            if (pack_loaded) {
                for (size_t li = 0; li < pack.levers.size() && li < pack.lever_meta.size(); ++li) {
                    if (pack.levers[li].id == lever_id) {
                        lmeta = &pack.lever_meta[li];
                        break;
                    }
                }
            }
            uint32_t horizon_ticks = 24;
            if (iss >> horizon_ticks) {
                if (horizon_ticks == 0) horizon_ticks = 1;
                if (horizon_ticks > 2000) horizon_ticks = 2000;
            }
            uint64_t custom_seed = 0;
            iss >> custom_seed;

            // ── Gerçek Paralel Motor Karşı-Olgusal Koşumu (Branch A vs Branch B) ──
            // Ana motorun durumu DEĞİŞMEZ; iki bağımsız klon üzerinde aynı başlangıç
            // durumundan (tick_start) ve aynı zamanlı intel akışından ilerlenir.
            caelus::causal::CausalEngine branch_a = engine;
            caelus::causal::CausalEngine branch_b = engine;
            const uint64_t tick_start = engine.current_tick();
            const uint64_t effective_seed = custom_seed != 0
                ? custom_seed
                : (engine.prng_seed() != 0 ? (engine.prng_seed() + tick_start) : (tick_start != 0 ? tick_start : 1ULL));

            const bool lever_applied_ok = branch_b.apply_lever(lever_id, effective_seed);

            caelus::causal::EngineSnapshot snap_a = last_snap;
            caelus::causal::EngineSnapshot snap_b = last_snap;
            double sum_tp_a = 0.0;
            double sum_tp_b = 0.0;
            uint32_t outage_ticks_a = 0;
            uint32_t outage_ticks_b = 0;

            for (uint32_t step = 0; step < horizon_ticks; ++step) {
                if (pack_loaded) {
                    pack.inject_intel_at(branch_a, branch_a.current_tick());
                    pack.inject_intel_at(branch_b, branch_b.current_tick());
                }
                snap_a = branch_a.tick();
                snap_b = branch_b.tick();
                sum_tp_a += snap_a.throughput_ratio;
                sum_tp_b += snap_b.throughput_ratio;
                if (snap_a.outage_active) ++outage_ticks_a;
                if (snap_b.outage_active) ++outage_ticks_b;
            }

            const double avg_tp_a = sum_tp_a / static_cast<double>(horizon_ticks);
            const double avg_tp_b = sum_tp_b / static_cast<double>(horizon_ticks);
            const double delta_tp = avg_tp_b - avg_tp_a;

            std::ostringstream cf;
            cf << std::fixed << std::setprecision(6)
               << "{\"type\":\"counterfactual_result\","
               << "\"scenario_id\":\"" << json_escape(g_scenario_id) << "\","
               << "\"lever_id\":\"" << json_escape(lever_id) << "\","
               << "\"lever_code\":\"" << json_escape(lmeta ? lmeta->code : lever_id) << "\","
               << "\"lever_label\":\"" << json_escape(lmeta ? lmeta->label : lever_id) << "\","
               << "\"lever_target\":\"" << json_escape(meta->target) << "\","
               << "\"lever_success_p\":" << caelus::causal::fp_to_d(meta->success_p_fp) << ","
               << "\"lever_cost_ticks\":" << meta->cost_ticks << ","
               << "\"lever_lockout_ticks\":" << meta->lockout_ticks << ","
               << "\"lever_cost_usd\":" << (lmeta ? lmeta->cost_usd : -1.0) << ","
               << "\"lever_success\":" << (lever_applied_ok ? "true" : "false") << ","
               << "\"seed\":" << effective_seed << ","
               << "\"tick_start\":" << tick_start << ","
               << "\"horizon_ticks\":" << horizon_ticks << ","
               << "\"tick_minutes\":" << (pack_loaded ? pack.tick_minutes : 15) << ","
               << "\"baseline_end_friction\":" << snap_a.clamped_friction_d() << ","
               << "\"intervention_end_friction\":" << snap_b.clamped_friction_d() << ","
               << "\"baseline_end_throughput\":" << snap_a.throughput_ratio << ","
               << "\"intervention_end_throughput\":" << snap_b.throughput_ratio << ","
               << "\"baseline_avg_throughput\":" << avg_tp_a << ","
               << "\"intervention_avg_throughput\":" << avg_tp_b << ","
               << "\"delta_avg_throughput\":" << delta_tp << ","
               << "\"baseline_outage_ticks\":" << outage_ticks_a << ","
               << "\"intervention_outage_ticks\":" << outage_ticks_b << ","
               << "\"baseline_end_outage\":" << (snap_a.outage_active ? "true" : "false") << ","
               << "\"intervention_end_outage\":" << (snap_b.outage_active ? "true" : "false") << ","
               << "\"initial_state\":{"
               << "\"tick\":" << tick_start << ","
               << "\"throughput_ratio\":" << last_snap.throughput_ratio << ","
               << "\"clamped_friction\":" << last_snap.clamped_friction_d() << ","
               << "\"raw_friction\":" << last_snap.raw_friction_d() << ","
               << "\"outage_active\":" << (engine.outage_active() ? "true" : "false") << ","
               << "\"regime_exceeded\":" << (engine.regime_exceeded() ? "true" : "false") << ","
               << "\"nodes\":";
            emit_engine_nodes_json_array(cf, engine);
            cf << "},"
               << "\"branch_a\":{"
               << "\"tick\":" << branch_a.current_tick() << ","
               << "\"tick_end\":" << branch_a.current_tick() << ","
               << "\"throughput_ratio\":" << snap_a.throughput_ratio << ","
               << "\"avg_throughput\":" << avg_tp_a << ","
               << "\"clamped_friction\":" << snap_a.clamped_friction_d() << ","
               << "\"raw_friction\":" << snap_a.raw_friction_d() << ","
               << "\"regime_exceeded\":" << (snap_a.regime_exceeded ? "true" : "false") << ","
               << "\"outage_active\":" << (snap_a.outage_active ? "true" : "false") << ","
               << "\"outage_ticks\":" << outage_ticks_a << ","
               << "\"deadline_missed\":" << (snap_a.any_deadline_missed ? "true" : "false") << ","
               << "\"any_deadline_missed\":" << (snap_a.any_deadline_missed ? "true" : "false") << ","
               << "\"any_hysteresis_flip\":" << (snap_a.any_hysteresis_flip ? "true" : "false") << ","
               << "\"nodes\":";
            emit_engine_nodes_json_array(cf, branch_a);
            cf << "},"
               << "\"branch_b\":{"
               << "\"tick\":" << branch_b.current_tick() << ","
               << "\"tick_end\":" << branch_b.current_tick() << ","
               << "\"lever_succeeded\":" << (lever_applied_ok ? "true" : "false") << ","
               << "\"throughput_ratio\":" << snap_b.throughput_ratio << ","
               << "\"avg_throughput\":" << avg_tp_b << ","
               << "\"clamped_friction\":" << snap_b.clamped_friction_d() << ","
               << "\"raw_friction\":" << snap_b.raw_friction_d() << ","
               << "\"regime_exceeded\":" << (snap_b.regime_exceeded ? "true" : "false") << ","
               << "\"outage_active\":" << (snap_b.outage_active ? "true" : "false") << ","
               << "\"outage_ticks\":" << outage_ticks_b << ","
               << "\"deadline_missed\":" << (snap_b.any_deadline_missed ? "true" : "false") << ","
               << "\"any_deadline_missed\":" << (snap_b.any_deadline_missed ? "true" : "false") << ","
               << "\"any_hysteresis_flip\":" << (snap_b.any_hysteresis_flip ? "true" : "false") << ","
               << "\"nodes\":";
            emit_engine_nodes_json_array(cf, branch_b);
            cf << "}"
               << "}";
            const std::string cf_json = cf.str();

            std::cout << "[REPL_COUNTERFACTUAL] " << cf_json << std::endl;
            if (g_emitter.connected()) {
                g_emitter.emit(cf_json);
            }
            audit_repl_event(command_line, engine, "counterfactual_ok");
            continue;
        }
        if (cmd == "reset") {
            if (pack_loaded) {
                pack.apply_to_engine(engine);
                // Senaryo replay'i de baştan başlat (aksi hâlde imleç ileride kalır).
                if (scenario_replay && !scenario_replay_path.empty()) {
                    scenario_replay->reload(scenario_replay_path.c_str(),
                                            ticks_per_hour_for(pack.tick_minutes));
                } else if (scenario_replay_path.empty()) {
                    pack.inject_intel_at(engine, engine.current_tick());
                }
                last_snap = run_tick();
                print_repl_snapshot(engine, last_snap);
                if (g_emitter.connected()) emit_ws_scenario_model(pack, pack_loaded);
                audit_repl_event(command_line, engine, "ok");
            } else {
                std::cout << "[REPL] Sifirlanacak yuklu senaryo yok.\n";
                audit_repl_event(command_line, engine, "error");
            }
            continue;
        }
        if (cmd == "clear_irrecoverable") {
            // Motor, geri kazanılamaz kesintiyi YALNIZ clear_irrecoverable=true
            // sonuçlu bir kaldıracın başarısıyla temizler. Bu komut eskiden
            // senaryoyu sessizce sıfırlıyordu (yanıltıcı); artık kurtarma
            // kaldıraçlarını listeler.
            std::cout << "[REPL] clear_irrecoverable dogrudan desteklenmez. Kurtarma yalniz "
                         "clear_irrecoverable=true sonuclu kaldiracla mumkundur.\n";
            bool any = false;
            if (pack_loaded) {
                for (const auto& lv : pack.levers) {
                    if (lv.on_success.clear_irrecoverable) {
                        std::cout << "  kurtarma kaldiraci: " << lv.id << "\n";
                        any = true;
                    }
                }
            }
            if (!any) std::cout << "  Bu senaryoda kurtarma kaldiraci tanimli degil.\n";
            audit_repl_event(command_line, engine, "unsupported");
            continue;
        }
        if (cmd == "scenario" || cmd == "load") {
            std::string new_id;
            iss >> new_id;
            // Yalnız düz senaryo kimliği kabul edilir (yol ayırıcı / '..' yok).
            const bool id_ok = !new_id.empty() && new_id.size() <= 96 &&
                std::all_of(new_id.begin(), new_id.end(), [](unsigned char c) {
                    return std::isalnum(c) || c == '_' || c == '-';
                });
            if (!id_ok) {
                std::cout << "[REPL] Gecersiz senaryo kimligi (yalniz A-Z a-z 0-9 _ -): "
                          << new_id << "\n";
                audit_repl_event(command_line, engine, "error");
                continue;
            }
            caelus::ScenarioPack next_pack;
            const std::string next_path = "scenarios/" + new_id + ".json";
            if (next_pack.load(next_path)) {
                if (neural_controller) neural_controller->force_symbolic_fallback();
                pack = std::move(next_pack);
                pack_loaded = true;
                scenario_id = pack.id;
                g_scenario_id = pack.id;
                pack.apply_to_engine(engine);
                // Önceki senaryonun replay olaylarını at, yenisininkini yükle.
                if (scenario_replay) {
                    scenario_replay_path = next_path;
                    if (!scenario_replay->reload(scenario_replay_path.c_str(),
                                                 ticks_per_hour_for(pack.tick_minutes))) {
                        std::cout << "[REPL] UYARI: senaryo replay kaydi yeniden yuklenemedi.\n";
                    }
                } else {
                    std::cout << "[REPL] UYARI: motor senaryosuz basladigi icin senaryo replay "
                                 "baglayicisi kayitli degil; intel_feed_sequence oynatilmayacak.\n";
                }
                emit_ws_scenario_loaded(pack);
                if (g_emitter.connected()) emit_ws_scenario_model(pack, pack_loaded);
                last_snap = run_tick();
                print_repl_snapshot(engine, last_snap);
                audit_repl_event(command_line, engine, "ok");
            } else {
                std::cout << "[REPL] Senaryo yuklenemedi: " << new_id << "\n";
                audit_repl_event(command_line, engine, "error");
            }
            continue;
        }
        if (cmd == "load_json") {
            std::string json_payload;
            std::getline(iss, json_payload);
            json_payload = trim_copy(json_payload);
            if (json_payload.empty() || json_payload.size() > 1048576) {
                std::cout << "[REPL] load_json: gecersiz veya bos JSON yuku.\n";
                audit_repl_event("load_json <invalid>", engine, "error");
                continue;
            }
            caelus::ScenarioPack next_pack;
            if (next_pack.load_from_string(json_payload, "<ws_json>", /*allow_interactive_unsigned=*/true)) {
                if (neural_controller) neural_controller->force_symbolic_fallback();
                pack = std::move(next_pack);
                pack_loaded = true;
                scenario_id = pack.id;
                g_scenario_id = pack.id;
                pack.apply_to_engine(engine);
                scenario_replay_path.clear();
                if (scenario_replay) {
                    scenario_replay->reload("", ticks_per_hour_for(pack.tick_minutes));
                }
                emit_ws_scenario_loaded(pack);
                if (g_emitter.connected()) emit_ws_scenario_model(pack, pack_loaded);
                pack.inject_intel_at(engine, engine.current_tick());
                last_snap = run_tick();
                print_repl_snapshot(engine, last_snap);
                audit_repl_event("load_json " + pack.id, engine, "ok");
            } else {
                std::cout << "[REPL] load_json: senaryo ayristirma veya imza dogrulama hatasi.\n";
                audit_repl_event("load_json <failed>", engine, "error");
            }
            continue;
        }
        if (cmd == "save_world") {
            std::string world_json;
            std::getline(iss, world_json);
            world_json = trim_copy(world_json);
            if (world_json.empty() || world_json.size() > 2097152 || world_json.front() != '{') {
                std::cout << "[REPL] save_world: gecersiz veya bos dunya JSON yuku.\n";
                audit_repl_event("save_world <invalid>", engine, "error");
                continue;
            }
            if (!IsCompleteJsonObjectText(world_json)) {
                // Kesik/bozuk yük asla diske yazılmaz (mevcut sağlam depo korunur).
                std::cout << "[REPL] save_world: JSON eksik/bozuk (kesik cerceve?) — mevcut depo korundu, yazilmadi.\n";
                audit_repl_event("save_world <incomplete>", engine, "error");
                if (g_emitter.connected()) {
                    g_emitter.emit("{\"type\":\"world_store_save_rejected\",\"reason\":\"incomplete_json\"}");
                }
                continue;
            }
            const std::string store_path    = "caelus_world_store.json";
            const std::string tmp_path      = "caelus_world_store.json.tmp";
            const std::string prev_path     = "caelus_world_store.prev.json";
            const std::string prev_tmp_path = "caelus_world_store.prev.json.tmp";

            auto replace_file_atomic = [](const std::string& src, const std::string& dst) -> bool {
#ifdef _WIN32
                if (MoveFileExA(src.c_str(), dst.c_str(), MOVEFILE_REPLACE_EXISTING | MOVEFILE_WRITE_THROUGH) != 0) {
                    return true;
                }
#endif
                std::remove(dst.c_str());
                return std::rename(src.c_str(), dst.c_str()) == 0;
            };

            // 1. Önce geçici dosyaya (.tmp) tam olarak yaz ve diske boşalt (flush).
            std::ofstream ofs(tmp_path, std::ios::binary | std::ios::trunc);
            if (!ofs) {
                audit_repl_event("save_world <tmp_open_error>", engine, "error");
                continue;
            }
            ofs.write(world_json.data(), static_cast<std::streamsize>(world_json.size()));
            ofs.flush();
            const bool write_ok = !ofs.fail();
            ofs.close();
            if (!write_ok) {
                std::remove(tmp_path.c_str());
                audit_repl_event("save_world <tmp_write_error>", engine, "error");
                continue;
            }

            // 2. Mevcut sağlam depoyu (.prev.json) geçici yedek üzerinden koru.
            {
                std::ifstream prev_check(store_path, std::ios::binary);
                if (prev_check) {
                    std::ostringstream pss;
                    pss << prev_check.rdbuf();
                    std::string existing_json = trim_copy(pss.str());
                    prev_check.close();
                    if (!existing_json.empty() && IsCompleteJsonObjectText(existing_json)) {
                        std::ofstream pofs(prev_tmp_path, std::ios::binary | std::ios::trunc);
                        if (pofs) {
                            pofs.write(existing_json.data(), static_cast<std::streamsize>(existing_json.size()));
                            pofs.flush();
                            const bool prev_ok = !pofs.fail();
                            pofs.close();
                            if (prev_ok) {
                                (void)replace_file_atomic(prev_tmp_path, prev_path);
                            } else {
                                std::remove(prev_tmp_path.c_str());
                            }
                        }
                    }
                }
            }

            // 3. Geçici dosyayı ana depo dosyasına atomik olarak taşı (Windows MoveFileExA / POSIX rename).
            if (replace_file_atomic(tmp_path, store_path)) {
                if (g_emitter.connected()) {
                    std::ostringstream ev;
                    ev << "{\"type\":\"world_store_saved\",\"bytes\":" << world_json.size()
                       << ",\"path\":\"caelus_world_store.json\",\"atomic\":true}";
                    g_emitter.emit(ev.str());
                }
                audit_repl_event("save_world", engine, "ok");
            } else {
                audit_repl_event("save_world <rename_error>", engine, "error");
            }
            continue;
        }
        if (cmd == "load_world") {
            auto read_valid_json_file = [](const std::string& path) -> std::string {
                std::ifstream f(path, std::ios::binary);
                if (!f) return "";
                std::ostringstream ss;
                ss << f.rdbuf();
                f.close();
                std::string cand = trim_copy(ss.str());
                if (!cand.empty() && IsCompleteJsonObjectText(cand)) {
                    return cand;
                }
                return "";
            };

            std::ifstream ifs("caelus_world_store.json", std::ios::binary);
            if (ifs) {
                std::ostringstream ss;
                ss << ifs.rdbuf();
                std::string world_json = trim_copy(ss.str());
                ifs.close();
                if (!world_json.empty() && !IsCompleteJsonObjectText(world_json)) {
                    // Bozuk depo: karantinaya al ve varsa sağlam .prev.json (veya .tmp) yedeğinden geri yükle.
                    const std::string quarantined = "caelus_world_store.corrupt.json";
                    std::remove(quarantined.c_str());
                    const bool moved = std::rename("caelus_world_store.json", quarantined.c_str()) == 0;

                    std::string recovered_json = read_valid_json_file("caelus_world_store.prev.json");
                    std::string recovered_src  = "caelus_world_store.prev.json";
                    if (recovered_json.empty()) {
                        recovered_json = read_valid_json_file("caelus_world_store.json.tmp");
                        recovered_src  = "caelus_world_store.json.tmp";
                    }

                    if (!recovered_json.empty()) {
                        std::ofstream rofs("caelus_world_store.json", std::ios::binary | std::ios::trunc);
                        if (rofs) {
                            rofs.write(recovered_json.data(), static_cast<std::streamsize>(recovered_json.size()));
                            rofs.flush();
                            rofs.close();
                        }
                        if (recovered_src == "caelus_world_store.json.tmp") {
                            std::remove("caelus_world_store.json.tmp");
                        }
                        std::cout << "[REPL] load_world: dunya deposu bozuk/kesik (" << world_json.size()
                                  << " bayt) — karantinaya alindi (" << quarantined
                                  << ") ve saglam yedekten (" << recovered_src << ") geri yuklendi.\n";
                        audit_repl_event("load_world <recovered_from_prev>", engine, "recovered");
                        if (g_emitter.connected()) {
                            std::string ev = "{\"type\":\"world_store_loaded\",\"found\":true,\"recoveredFromBackup\":true,\"recoverySource\":\"" + recovered_src + "\",\"path\":\"caelus_world_store.json\",\"store\":" + recovered_json + "}";
                            g_emitter.emit(ev);
                        }
                        continue;
                    }

                    std::cout << "[REPL] load_world: dunya deposu bozuk/kesik (" << world_json.size()
                              << " bayt) — " << (moved ? "karantinaya alindi: " + quarantined : std::string("tasinamadi"))
                              << "; temiz dunya ile devam ediliyor.\n";
                    audit_repl_event("load_world <corrupt>", engine, "quarantined");
                    if (g_emitter.connected()) {
                        g_emitter.emit("{\"type\":\"world_store_loaded\",\"path\":\"caelus_world_store.json\",\"store\":null,\"corrupt\":true}");
                    }
                    continue;
                }
                if (!world_json.empty() && world_json.front() == '{') {
                    // Ana dosya sağlam; yarım kalmış .tmp varsa temizle.
                    std::remove("caelus_world_store.json.tmp");
                    if (g_emitter.connected()) {
                        std::string ev = "{\"type\":\"world_store_loaded\",\"found\":true,\"path\":\"caelus_world_store.json\",\"store\":" + world_json + "}";
                        g_emitter.emit(ev);
                    }
                    audit_repl_event("load_world", engine, "ok");
                    continue;
                }
            }

            // Ana dosya (caelus_world_store.json) eksik veya boş:
            // Önce yarım kalan taşıma (.tmp) içinde tam JSON var mı kontrol et (son kayıt v2),
            // yoksa .prev.json yedeğini kontrol et (önceki kayıt v1).
            std::string fallback_json = read_valid_json_file("caelus_world_store.json.tmp");
            std::string fallback_src  = "caelus_world_store.json.tmp";
            if (fallback_json.empty()) {
                fallback_json = read_valid_json_file("caelus_world_store.prev.json");
                fallback_src  = "caelus_world_store.prev.json";
            }
            if (!fallback_json.empty()) {
                std::ofstream rofs("caelus_world_store.json", std::ios::binary | std::ios::trunc);
                if (rofs) {
                    rofs.write(fallback_json.data(), static_cast<std::streamsize>(fallback_json.size()));
                    rofs.flush();
                    rofs.close();
                }
                if (fallback_src == "caelus_world_store.json.tmp") {
                    std::remove("caelus_world_store.json.tmp");
                }
                std::cout << "[REPL] load_world: ana depo eksik — saglam kayittan (" << fallback_src << ") geri yuklendi.\n";
                audit_repl_event("load_world <recovered_missing_main>", engine, "recovered");
                if (g_emitter.connected()) {
                    std::string ev = "{\"type\":\"world_store_loaded\",\"found\":true,\"recoveredFromBackup\":true,\"recoverySource\":\"" + fallback_src + "\",\"path\":\"caelus_world_store.json\",\"store\":" + fallback_json + "}";
                    g_emitter.emit(ev);
                }
            } else {
                if (g_emitter.connected()) {
                    g_emitter.emit("{\"type\":\"world_store_loaded\",\"path\":\"caelus_world_store.json\",\"store\":null}");
                }
            }
            continue;
        }

        std::cout << "[REPL] Bilinmeyen komut: " << cmd << " (yardim: help)\n";
        audit_repl_event(command_line, engine, "error");
    }

    return last_snap;
}

static int PrintScenarioCanonicalPayload(const std::string& path) {
    std::string payload;
    std::string error;
    if (!caelus::ScenarioPack::canonical_signed_payload_from_file(path, payload, &error)) {
        std::cerr << "[SIGNER] Canonical payload üretilemedi: " << error << "\n";
        return 2;
    }
    std::cout << payload;
    return 0;
}

static int ReportScenarioSignerBlocked(const std::string& path,
                                       const std::string& key_path) {
    (void)key_path;
    std::string payload;
    std::string error;
    if (!caelus::ScenarioPack::canonical_signed_payload_from_file(path, payload, &error)) {
        std::cerr << "[SIGNER] Imzalanacak payload üretilemedi: " << error << "\n";
        return 2;
    }
    std::cerr
        << "[SIGNER] BLOCKER: Bu binary içinde export edilmiş ed25519 signing FFI sembolü yok.\n"
        << "         Mevcut Rust FFI yalnız doğrulama sağlıyor "
        << "(caelus_verify_scenario_signature); C++ tarafında seed ile imza atacak\n"
        << "         hazır fonksiyon bulunmadığı için iki dosya sınırında gerçek imza üretilemiyor.\n"
        << "         Payload almak için: --print-scenario-payload <json>\n";
    return 3;
}

