//! Zero-allocation embedded 6x10 bitmap glyph renderer for Warm Swiss UI.
//! Eliminates `fontdb` / OS font mmap overhead while supporting ASCII, Turkish
//! diacritics, and clean 7-locale Latin/Greek/Cyrillic display.

use crate::theme::RgbaColor;
use tiny_skia::PixmapMut;

pub const GLYPH_W: u32 = 6;
pub const GLYPH_H: u32 = 10;
pub const GLYPH_ADVANCE: u32 = 7;
pub const LINE_HEIGHT: u32 = 14;

/// Draws crisp monospace text directly into `pixmap` clipped to canvas bounds.
/// Zero heap allocations during rendering.
pub fn draw_text(
    pixmap: &mut PixmapMut<'_>,
    x: i32,
    y: i32,
    text: &str,
    scale: u32,
    color: RgbaColor,
    bold: bool,
) {
    let s = scale.max(1) as i32;
    let pw = pixmap.width() as i32;
    let ph = pixmap.height() as i32;
    let data = pixmap.data_mut();
    let adv = (GLYPH_ADVANCE as i32) * s;
    let lh = (LINE_HEIGHT as i32) * s;

    let mut cx = x;
    let mut cy = y;

    for ch in text.chars() {
        if ch == '\n' {
            cx = x;
            cy += lh;
            continue;
        }
        let mut buf = [0u8; 4];
        let mapped = map_char_slice(ch, &mut buf);
        for &mch in mapped {
            if cx + (GLYPH_W as i32) * s >= 0
                && cx < pw
                && cy + (GLYPH_H as i32) * s >= 0
                && cy < ph
            {
                let rows = glyph_rows(mch);
                blit_glyph(data, pw, ph, cx, cy, s, &rows, color, bold);
            }
            cx += adv;
        }
    }
}

/// Measures rendered text bounding `(width, height)` in pixels.
#[must_use]
pub fn measure_text(text: &str, scale: u32) -> (f32, f32) {
    let s = scale.max(1);
    let mut max_cols = 0usize;
    let mut cur_cols = 0usize;
    let mut lines = 1usize;
    let mut buf = [0u8; 4];

    for ch in text.chars() {
        if ch == '\n' {
            max_cols = max_cols.max(cur_cols);
            cur_cols = 0;
            lines += 1;
        } else {
            cur_cols += map_char_slice(ch, &mut buf).len();
        }
    }
    max_cols = max_cols.max(cur_cols);
    let w = if max_cols == 0 {
        0.0
    } else {
        (max_cols as f32) * (GLYPH_ADVANCE as f32) * (s as f32) - (s as f32)
    };
    let h = (lines as f32) * (GLYPH_H as f32) * (s as f32)
        + ((lines.saturating_sub(1)) as f32) * ((LINE_HEIGHT - GLYPH_H) as f32) * (s as f32);
    (w, h)
}

#[inline]
#[allow(clippy::too_many_arguments)]
fn blit_glyph(
    rgba: &mut [u8],
    pw: i32,
    ph: i32,
    gx: i32,
    gy: i32,
    scale: i32,
    rows: &[u8; 10],
    color: RgbaColor,
    bold: bool,
) {
    let sa = color.a as u32;
    if sa == 0 {
        return;
    }
    let inv_a = 255 - sa;
    for (row_idx, &bits) in rows.iter().enumerate() {
        if bits == 0 {
            continue;
        }
        let py_base = gy + (row_idx as i32) * scale;
        for col in 0..6i32 {
            let set = ((bits >> (5 - col)) & 1) != 0;
            let bold_set = bold && col > 0 && ((bits >> (6 - col)) & 1) != 0;
            if !set && !bold_set {
                continue;
            }
            let px_base = gx + col * scale;
            for sy in 0..scale {
                let py = py_base + sy;
                if py < 0 || py >= ph {
                    continue;
                }
                for sx in 0..scale {
                    let px = px_base + sx;
                    if px < 0 || px >= pw {
                        continue;
                    }
                    let idx = ((py * pw + px) as usize) * 4;
                    if sa == 255 {
                        rgba[idx] = color.r;
                        rgba[idx + 1] = color.g;
                        rgba[idx + 2] = color.b;
                        rgba[idx + 3] = 255;
                    } else {
                        rgba[idx] = ((color.r as u32 * sa + rgba[idx] as u32 * inv_a) / 255) as u8;
                        rgba[idx + 1] =
                            ((color.g as u32 * sa + rgba[idx + 1] as u32 * inv_a) / 255) as u8;
                        rgba[idx + 2] =
                            ((color.b as u32 * sa + rgba[idx + 2] as u32 * inv_a) / 255) as u8;
                        rgba[idx + 3] = 255;
                    }
                }
            }
        }
    }
}

